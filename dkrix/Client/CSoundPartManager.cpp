#include "Client_PCH.h"
#include "CSoundPartManager.h"

//-----------------------------------------------------------------------------
// Release
//-----------------------------------------------------------------------------
void
CSoundPartManager::Release()
{
	//---------------------------------------------------
	
	//---------------------------------------------------
	if (m_pData!=NULL)
	{
		for (int i=0; i<m_nPart; i++)
		{
			if (m_pData[i]!=NULL)
			{
#ifdef PLATFORM_WINDOWS
				m_pData[i]->Stop();
				m_pData[i]->Release();
#endif
				m_pData[i] = NULL;
			}
		}
	}

	//---------------------------------------------------
	// base class release
	//---------------------------------------------------
	CPartManager<WORD, BYTE, LPDIRECTSOUNDBUFFER>::Release();
}

//-----------------------------------------------------------------------------
// Stop
//-----------------------------------------------------------------------------
void
CSoundPartManager::Stop()
{
	//---------------------------------------------------
	
	//---------------------------------------------------
	if (m_pData!=NULL)
	{
		for (int i=0; i<m_nPart; i++)
		{
			if (m_pData[i]!=NULL)
			{
#ifdef PLATFORM_WINDOWS
				m_pData[i]->Stop();
#endif
			}
		}
	}
}