//----------------------------------------------------------------------
// Release
//----------------------------------------------------------------------
void				
MStringMap::Release()
{
	STRING_MAP::iterator iString = begin();

	while (iString != end())
	{
		MString* pKey	= iString->first;
		MString* pValue = iString->second;
		
		//--------------------------------------------------------
		
		
		//--------------------------------------------------------
		if (pKey==pValue)
		{
			if (pKey!=NULL)
			{
				delete pKey;
			}
		}
		//--------------------------------------------------------
		
		//--------------------------------------------------------
		else
		{
			if (pKey!=NULL)
			{
				delete pKey;
			}

			if (pValue!=NULL)
			{
				delete pValue;
			}
		}

		iString++;
	}

	
	clear();
}

